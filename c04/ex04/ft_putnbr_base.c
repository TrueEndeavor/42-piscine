#include <unistd.h>

void	ft_putchar(char c)
{
	write(1, &c, 1);
}

int	ft_strlen(char *str)
{
	int		i;

	i = 0;
	while (str[i])
	{
		i++;
	}
	return (i);
}

int	ft_check_base(char *base)
{
	int		i;
	int		j;

	if (ft_strlen(base) < 2)
		return (0);
	i = 0;
	while (base[i])
	{
		if (base[i] == '-' || base[i] == '+' || base[i] < 32 || base[i] > 126)
			return (0);
		j = i + 1;
		while (base[j])
		{
			if (base[i] == base[j])
				return (0);
			j++;
		}
		i++;
	}
	return (1);
}

void	ft_putnbr_base(int nbr, char *base)
{
	long	quotient;
	char	result[32];
	int		base_len;
	int		i;

	if (!ft_check_base(base))
		return ;
	base_len = ft_strlen(base);
	if (nbr < 0)
	{
		quotient = nbr;
		quotient = -quotient;
		ft_putchar('-');
	}
	else
		quotient = nbr;
	i = 0;
	while (quotient > 0)
	{
		result[i] = base[quotient % base_len];
		quotient /= base_len;
		i++;
	}
	while (--i >= 0)
		ft_putchar(result[i]);
}
